CREATE TABLE MERCHANT (
    MerchantID INT AUTO_INCREMENT PRIMARY KEY,
    MerchantName VARCHAR(100) NOT NULL,
    Website VARCHAR(255),
    ContactEmail VARCHAR(150)
);

CREATE TABLE REPLACEMENT_OPTION (
    OptionID INT AUTO_INCREMENT PRIMARY KEY,
    RuleID INT NOT NULL,
    MerchantID INT NOT NULL,
    ProductName VARCHAR(100) NOT NULL,
    ProductType VARCHAR(100),
    EstimatedPrice DECIMAL(10,2),
    ProductURL VARCHAR(255),
    FOREIGN KEY (RuleID) REFERENCES DECISION_RULE(RuleID),
    FOREIGN KEY (MerchantID) REFERENCES MERCHANT(MerchantID)
);

CREATE TABLE FEEDBACK (
    FeedbackID INT AUTO_INCREMENT PRIMARY KEY,
    ReportID INT NOT NULL,
    UserID INT NOT NULL,
    FeedbackType VARCHAR(50),
    Comments TEXT,
    Rating INT,
    SubmittedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (ReportID) REFERENCES PROBLEM_REPORT(ReportID),
    FOREIGN KEY (UserID) REFERENCES USER(UserID)
);