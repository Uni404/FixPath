USE fixpath_db;

CREATE TABLE USER (
    UserID INT AUTO_INCREMENT PRIMARY KEY,
    Name VARCHAR(100) NOT NULL,
    Email VARCHAR(150) NOT NULL UNIQUE,
    PasswordHash VARCHAR(255) NOT NULL,
    CreatedTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE DEVICE_CATEGORY (
    CategoryID INT AUTO_INCREMENT PRIMARY KEY,
    CategoryName VARCHAR(100) NOT NULL,
    CategoryDescription TEXT
);

CREATE TABLE DEVICE (
    DeviceID INT AUTO_INCREMENT PRIMARY KEY,
    CategoryID INT NOT NULL,
    DeviceName VARCHAR(100) NOT NULL,
    Manufacturer VARCHAR(100),
    Model VARCHAR(100),
    DeviceDescription TEXT,
    FOREIGN KEY (CategoryID) REFERENCES DEVICE_CATEGORY(CategoryID)
);

CREATE TABLE SYMPTOM (
    SymptomID INT AUTO_INCREMENT PRIMARY KEY,
    SymptomName VARCHAR(100) NOT NULL,
    SymptomDescription TEXT,
    SeverityLevel VARCHAR(50)
);

CREATE TABLE PROBLEM_REPORT (
    ReportID INT AUTO_INCREMENT PRIMARY KEY,
    UserID INT NOT NULL,
    DeviceID INT NOT NULL,
    ReportDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ProblemDescription TEXT NOT NULL,
    DetectedRiskLevel VARCHAR(50),
    Status VARCHAR(50),
    MediaURL VARCHAR(255),
    FOREIGN KEY (UserID) REFERENCES USER(UserID),
    FOREIGN KEY (DeviceID) REFERENCES DEVICE(DeviceID)
);

CREATE TABLE PROBLEM_REPORT_SYMPTOM (
    ReportID INT NOT NULL,
    SymptomID INT NOT NULL,
    Notes TEXT,
    PRIMARY KEY (ReportID, SymptomID),
    FOREIGN KEY (ReportID) REFERENCES PROBLEM_REPORT(ReportID),
    FOREIGN KEY (SymptomID) REFERENCES SYMPTOM(SymptomID)
);

CREATE TABLE DECISION_RULE (
    RuleID INT AUTO_INCREMENT PRIMARY KEY,
    DeviceID INT NOT NULL,
    OutcomeType VARCHAR(100) NOT NULL,
    GuidanceText TEXT,
    RiskLevel VARCHAR(50),
    Priority INT,
    RequiresExpert BOOLEAN DEFAULT FALSE,
    IsActive BOOLEAN DEFAULT TRUE,
    FOREIGN KEY (DeviceID) REFERENCES DEVICE(DeviceID)
);

CREATE TABLE RULE_SYMPTOM (
    RuleID INT NOT NULL,
    SymptomID INT NOT NULL,
    PRIMARY KEY (RuleID, SymptomID),
    FOREIGN KEY (RuleID) REFERENCES DECISION_RULE(RuleID),
    FOREIGN KEY (SymptomID) REFERENCES SYMPTOM(SymptomID)
);

CREATE TABLE DECISION_RESULT (
    ResultID INT AUTO_INCREMENT PRIMARY KEY,
    ReportID INT NOT NULL,
    RuleID INT,
    Outcome VARCHAR(100) NOT NULL,
    Recommendation TEXT,
    ResultDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RiskLevel VARCHAR(50),
    FOREIGN KEY (ReportID) REFERENCES PROBLEM_REPORT(ReportID),
    FOREIGN KEY (RuleID) REFERENCES DECISION_RULE(RuleID)
);